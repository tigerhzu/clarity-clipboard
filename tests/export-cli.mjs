// Native executable test. Overrides APPDATA; never starts the UI or reads real clips.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { DatabaseSync } from "node:sqlite";
const exe = path.resolve(process.argv[2] || "src-tauri/target/release/clarity-clipboard.exe");
assert.ok(fs.existsSync(exe), "Build the new executable first");
const root = fs.mkdtempSync(path.resolve("src-tauri/target/export-cli-"));
const appdata = path.join(root, "appdata");
const data = path.join(appdata, "com.tigerhzu.clarityclipboard");
fs.mkdirSync(path.join(data, "images"), { recursive: true });
const dbPath = path.join(data, "clipboard.db");
const db = new DatabaseSync(dbPath);
for (const table of ["clipboard_items", "folder_items", "personal_items"]) {
  db.exec(`CREATE TABLE ${table} (id TEXT, custom_name TEXT, title TEXT, content TEXT, content_type TEXT, created_at INTEGER, source_app TEXT, file_path TEXT, tags TEXT, folder_id TEXT)`);
}
db.exec("CREATE TABLE folders (id TEXT, name TEXT)");
const created = new Date(2026, 10, 16, 12).getTime();
db.prepare("INSERT INTO clipboard_items (id,content,content_type,created_at,tags) VALUES (?,?,?,?,?)").run("text", '中文,\"CSV\"\n第二行', "TEXT", created, '["工作","報告"]');
db.prepare("INSERT INTO clipboard_items (id,custom_name,content,content_type,created_at) VALUES (?,?,?,?,?)").run("text-2", "彩色分類範例", "每種類型有自己的分頁，交錯底色讓內容更容易閱讀。", "TEXT", created + 1);
db.prepare("INSERT INTO clipboard_items (id,custom_name,content,content_type,created_at) VALUES (?,?,?,?,?)").run("url", "範例網址", "https://example.com", "URL", created + 2);
const imagePath = path.join(data, "images", "fixture.png");
const image = fs.readFileSync("src-tauri/icons/128x128.png");
fs.writeFileSync(imagePath, image);
db.prepare("INSERT INTO clipboard_items (id,content_type,created_at,file_path) VALUES (?,?,?,?)").run("image", "IMAGE", created, imagePath);
db.prepare("INSERT INTO clipboard_items (id,content,content_type,created_at) VALUES (?,?,?,?)").run("next-day", "隔日工作筆記", "TEXT", new Date(2026, 10, 17, 0).getTime());
db.close();
const original = fs.readFileSync(dbPath);
const options = ["--start", "2026-11-16", "--end", "2026-11-16", "--output", path.join(root, "reports")];
const run = (args, entry = "--export-excel") => spawnSync(exe, [entry, ...args], { env: { ...process.env, APPDATA: appdata }, encoding: "utf8", windowsHide: true, timeout: 30000 });
const child = run(options);
assert.equal(child.status, 0, child.stderr);
const result = JSON.parse(child.stdout);
assert.equal(JSON.parse(fs.readFileSync(path.join(result.directory, 'manifest.json'), 'utf8')).status, 'complete');
assert.deepEqual([result.itemCount, result.rowCount, result.imageCount, result.sheetCount, result.embeddedImageCount], [4, 5, 1, 4, 1]);
assert.equal(fs.readFileSync(result.xlsxPath).subarray(0, 2).toString(), "PK", "XLSX must be a ZIP workbook, not renamed CSV");
const daily = run(["--start", "2026-11-16", "--end", "2026-11-17", "--output", path.join(root, "daily"), "--group-by", "date"]);
assert.equal(daily.status, 0, daily.stderr);
const dailyResult = JSON.parse(daily.stdout);
fs.writeFileSync(path.join(root, "overview-path.txt"), dailyResult.xlsxPath);
assert.deepEqual([dailyResult.itemCount, dailyResult.sheetCount, dailyResult.embeddedImageCount], [5, 4, 1]);
assert.equal(JSON.parse(fs.readFileSync(path.join(dailyResult.directory, "manifest.json"), "utf8")).layout, "dateOverviewAndTypes");
assert.equal(run([...options, "--group-by", "invalid"]).status, 1);
const legacy = run([...options, "--tag", "IMAGE"], "--export-csv");
assert.equal(legacy.status, 0, legacy.stderr);
assert.ok(fs.existsSync(JSON.parse(legacy.stdout).xlsxPath));
assert.deepEqual(result.warnings, []);
assert.ok(fs.readFileSync(result.csvPath, "utf8").includes('中文,""CSV""\n第二行'));
assert.deepEqual(fs.readFileSync(path.join(result.directory, "images", fs.readdirSync(path.join(result.directory, "images"))[0])), image);
assert.deepEqual(fs.readFileSync(dbPath), original);
assert.equal(fs.existsSync(path.join(data, "settings.json")), false);
assert.equal(fs.existsSync(path.join(data, "hermes-bridge.json")), false);
assert.equal(run(["--start", "bad"]).status, 1);
assert.equal(run([...options, "--storage", "invalid"]).status, 1);
assert.equal(run([...options, "--output", path.join(root, "duplicate")]).status, 1);
const empty = run(["--start", "2026-11-15", "--end", "2026-11-15", "--output", path.join(root, "reports")]);
assert.equal(JSON.parse(empty.stdout).itemCount, 0);
const script = spawnSync("powershell.exe", ["-NoProfile", "-File", path.resolve("scripts/export-clipboard.ps1"), "-Executable", exe, "-StartDate", "2026-11-16", "-EndDate", "2026-11-16", "-OutputDirectory", path.join(root, "script"), "-Tag", "IMAGE", "-GroupBy", "date"], { env: { ...process.env, APPDATA: appdata }, encoding: "utf8", windowsHide: true, timeout: 30000 });
assert.equal(script.status, 0, script.stderr);
const scriptResult = JSON.parse(script.stdout);
assert.ok(fs.existsSync(scriptResult.csvPath), "PowerShell must preserve Unicode output paths in JSON");
assert.ok(fs.existsSync(scriptResult.xlsxPath));
const folders = fs.readdirSync(path.join(root, "script"));
assert.equal(folders.length, 1);
const manifest = JSON.parse(fs.readFileSync(path.join(root, "script", folders[0], "manifest.json"), "utf8"));
assert.equal(manifest.result.imageCount, 1);
assert.equal(manifest.result.itemCount, 1);
assert.equal(manifest.status, 'complete');
assert.equal(manifest.layout, 'dateOverviewAndTypes');
console.log(`PASS native Excel/CSV CLI, stdout JSON, image bytes, read-only DB, failures, empty results and PowerShell wrapper. Workbook: ${result.xlsxPath}
Two-day overview: ${dailyResult.xlsxPath}`);
